import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { chromium, expect } from '@playwright/test';
import { projectFixture } from '../../../kenvoy-tests/browser/fixture.mjs';

const fixture = await projectFixture();
let browser;
const output = fileURLToPath(new URL('../../../../artifacts/phase06/', import.meta.url));
await mkdir(output, { recursive: true });
try {
  await fixture.command(['--project', 'app', 'admin', 'init', '--username', 'admin', '--password-stdin'], 'browser-only-test-password-729\n');
  const server = await fixture.start();
  browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, locale: 'zh-CN' });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(server.origin + '/customers');
  await expect(page.getByRole('heading', { name: '客户登记', exact: true })).toBeVisible();
  await expect(page.getByLabel('客户姓名', { exact: false })).toBeVisible();
  await page.screenshot({ path: output + '/form-desktop.png', fullPage: true, animations: 'disabled' });
  await page.getByRole('button', { name: '提交信息', exact: true }).click();
  await expect(page.getByLabel('客户姓名', { exact: false })).toHaveAttribute('aria-invalid', 'true');
  await page.getByLabel('客户姓名', { exact: false }).fill('张'.repeat(101));
  await page.getByLabel('年龄', { exact: false }).fill('-1');
  await page.getByRole('button', { name: '提交信息', exact: true }).click();
  await expect(page.getByLabel('客户姓名', { exact: false })).toHaveAttribute('aria-invalid', 'true');
  await expect(page.getByLabel('年龄', { exact: false })).toHaveAttribute('aria-invalid', 'true');
  await page.getByLabel('客户姓名', { exact: false }).fill('张三');
  await page.getByLabel('联系电话', { exact: false }).fill('13800000000');
  await page.getByLabel('年龄', { exact: false }).fill('25.5');
  await page.getByRole('button', { name: '提交信息', exact: true }).click();
  await expect(page.getByLabel('年龄', { exact: false })).toHaveAttribute('aria-invalid', 'true');
  await page.getByLabel('年龄', { exact: false }).fill('25');
  const submitted = page.waitForResponse(response => response.url().endsWith('/api/customers') && response.request().method() === 'POST');
  await page.getByRole('button', { name: '提交信息', exact: true }).click();
  const response = await submitted; assert.equal(response.status(), 201);
  const record = (await response.json()).data;
  assert.equal(record.name, '张三'); assert.equal(record.age, 25);
  await expect(page.getByText('提交成功', { exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: '再登记一条', exact: true })).toBeVisible();
  await page.screenshot({ path: output + '/form-success.png', fullPage: true, animations: 'disabled' });
  const anonymous = await page.request.get(server.origin + '/api/customers'); assert.equal(anonymous.status(), 401);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: '再登记一条', exact: true }).click();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false);
  await page.screenshot({ path: output + '/form-mobile.png', fullPage: true, animations: 'disabled' });
  await page.getByRole('button', { name: '打开导航', exact: true }).click();
  await expect(page.getByRole('dialog', { name: '导航', exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: '关闭', exact: true })).toBeFocused();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect(page.getByRole('button', { name: '打开导航', exact: true })).toBeFocused();
  await page.goto(server.origin + '/admin/login');
  await page.getByLabel('用户名', { exact: false }).fill('admin');
  await page.getByLabel('密码', { exact: false }).fill('browser-only-test-password-729');
  await page.getByRole('button', { name: '登录', exact: true }).click();
  await expect(page.getByRole('heading', { name: '客户', exact: true })).toBeVisible();
  const listed = await page.request.get(server.origin + '/api/customers'); assert.equal(listed.status(), 200);
  assert.equal((await listed.json()).data[0].id, record.id);
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ status: '通过', browser: browser.version(), real_form_sqlite: true, required_length_integer_min: true, administrator_login: true, desktop_mobile: true, screenshots: output }, null, 2));
  await server.stop();
} finally { try { if (browser) await browser.close(); } finally { await fixture.close(); } }
